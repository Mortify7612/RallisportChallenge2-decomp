#!/usr/bin/env python3
"""Writes kernel/nv2a_gl_queue.h: a queued wrapper for each GL entry point
nv2a_gl.c loads (its GL_FNS list), from the prototypes in glcorearb.h.

    python3 xboxrecomp/tools/gen_gl_queue.py [path/to/glcorearb.h]

A call that returns nothing and passes no pointer (or only a buffer offset
dressed as one: glDrawElements' indices, glVertexAttribPointer's pointer)
is copied into the queue and the caller goes on; anything else -- a result
to return, memory to read or write -- waits for the GL thread to reach it
and make it (glq_call). The queue itself is in nv2a_gl.c (glq_*)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src', 'kernel', 'nv2a_gl.c')
OUT = os.path.join(HERE, '..', 'src', 'kernel', 'nv2a_gl_queue.h')
OFFSET_PTR = {('glDrawElements', 'indices'), ('glVertexAttribPointer', 'pointer')}


def gl_fns(src):
    block = re.search(r'#define GL_FNS\(X\)(.*?)\n\n', src, re.S).group(1)
    return re.findall(r'X\(PFN\w+PROC, (\w+)\)', block)


def prototypes(header):
    protos = {}
    for m in re.finditer(r'GLAPI[ \t]+([^\n;#]+?)\s*APIENTRY\s+(\w+)\s*\((.*?)\);', header, re.S):
        ret, name, params = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
        args = []
        if params != 'void':
            for p in params.split(','):
                p = p.strip()
                pm = re.match(r'(.*?)(\w+)$', p)
                args.append((pm.group(1).strip(), pm.group(2)))
        protos[name] = (ret, args)
    return protos


def main():
    header = sys.argv[1] if len(sys.argv) > 1 else '/usr/include/GL/glcorearb.h'
    names = gl_fns(open(SRC).read())
    protos = prototypes(open(header).read())
    out = ['/* Generated by xboxrecomp/tools/gen_gl_queue.py from nv2a_gl.c\'s GL_FNS',
           ' * and glcorearb.h: do not edit. Each GL call the renderer makes, queued',
           ' * for the GL thread (nv2a_gl.c, glq_*) when the queue is on. */', '']
    for name in names:
        ret, args = protos[name]
        sig = ', '.join('%s %s' % (t, a) for t, a in args) or 'void'
        call = ', '.join(a for _, a in args)
        ptr = any('*' in t and (name, a) not in OFFSET_PTR for t, a in args)
        queued = ret == 'void' and not ptr
        fields = ''.join('    %s %s;\n' % (t, a) for t, a in args)
        unpack = ', '.join('q->%s' % a for _, a in args)
        if queued:
            out.append('struct qa_%s {\n%s    int unused_;\n};' % (name, fields))
            out.append('static void qrun_%s(const void *p)\n{\n'
                       '    const struct qa_%s *q = (const struct qa_%s *)p;\n'
                       '    (void)q;\n    p_%s(%s);\n}' % (name, name, name, name, unpack))
            sets = ''.join('    q->%s = %s;\n' % (a, a) for _, a in args)
            out.append('static inline void APIENTRY q_%s(%s)\n{\n    struct qa_%s *q;\n'
                       '    if (glq_direct()) {\n        p_%s(%s);\n        return;\n    }\n'
                       '    q = (struct qa_%s *)glq_alloc(qrun_%s, sizeof *q);\n%s'
                       '    glq_commit();\n}' % (name, sig, name, name, call, name, name, sets))
        else:
            rfield = '' if ret == 'void' else '    %s r_;\n' % ret
            assign = '' if ret == 'void' else 'q->r_ = '
            out.append('struct qs_%s {\n%s%s    int unused_;\n};' % (name, fields, rfield))
            out.append('static void qrun_%s(void *p)\n{\n'
                       '    struct qs_%s *q = (struct qs_%s *)p;\n'
                       '    (void)q;\n    %sp_%s(%s);\n}' % (name, name, name, assign, name, unpack))
            body = '    struct qs_%s q;\n    memset(&q, 0, sizeof q);\n' % name
            body += ''.join('    q.%s = %s;\n' % (a, a) for _, a in args)
            if ret == 'void':
                out.append('static inline void APIENTRY q_%s(%s)\n{\n'
                           '    if (glq_direct()) {\n        p_%s(%s);\n        return;\n    }\n'
                           '%s    glq_call(qrun_%s, &q, "%s");\n}' % (name, sig, name, call, body, name, name))
            else:
                out.append('static inline %s APIENTRY q_%s(%s)\n{\n'
                           '    if (glq_direct())\n        return p_%s(%s);\n'
                           '%s    glq_call(qrun_%s, &q, "%s");\n    return q.r_;\n}'
                           % (ret, name, sig, name, call, body, name, name))
        out.append('#undef %s\n#define %s q_%s\n' % (name, name, name))
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote %s: %d entry points' % (OUT, len(names)))


if __name__ == '__main__':
    main()
