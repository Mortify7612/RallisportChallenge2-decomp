/* RSC2_PADWATCH=1: twice a second, the game's four pad slots -- the array at
 * *(0x0041D8E8), 0x10C bytes each -- as XInputGetState left them (+0x04
 * packet, +0x08 wButtons) and as the game's own button masks (+0xB8 current,
 * +0xBC previous) after mapping. Printed only when something changed. */
static void *padwatch_thread(void *unused)
{
    uint32_t last[4][3] = {{0}};
    (void)unused;
    for (;;) {
        uint32_t base, i;
        usleep(500000);
        {
            static uint32_t last_dev, last_sig;
            uint32_t dev = *(volatile uint32_t *)((uintptr_t)g_xbox_mem_offset + 0x00375418u);
            uint32_t sig = dev ? *(volatile uint32_t *)((uintptr_t)g_xbox_mem_offset + dev + 0x1DC0u) : 0;
            uint32_t hdr = dev ? *(volatile uint32_t *)((uintptr_t)g_xbox_mem_offset + dev + 0x1DBCu) : 0;
            if (dev != last_dev || sig != last_sig) {
                fprintf(stderr, "[PADWATCH] d3d device=%08X vblank event %08X hdr=%08X signal=%u\n",
                        dev, dev + 0x1DBCu, hdr, sig);
                last_dev = dev; last_sig = sig;
            }
        }
        base = *(volatile uint32_t *)((uintptr_t)g_xbox_mem_offset + 0x0041D8E8u);
        if (!base || base >= 0x04000000u) continue;
        for (i = 0; i < 4; i++) {
            const volatile uint32_t *p =
                (const volatile uint32_t *)((uintptr_t)g_xbox_mem_offset + base + i * 0x10Cu);
            uint32_t h = p[0], btn = p[2] & 0xFFFF, cur = p[0xB8 / 4];
            if (h != last[i][0] || btn != last[i][1] || cur != last[i][2]) {
                fprintf(stderr, "[PADWATCH] slot %u handle=%08X pkt=%u xbtn=%04X "
                        "cur=%08X prev=%08X\n", i, h, p[1], btn, cur, p[0xBC / 4]);
                last[i][0] = h; last[i][1] = btn; last[i][2] = cur;
            }
        }
    }
    return NULL;
}

/* `kill -QUIT <pid>`: every thread prints its native backtrace to stderr.
 *
 * The answer to "where is it stuck" without a debugger. gdb cannot stand in
 * here: the AC'97 emulation single-steps trapped writes with TF, and gdb
 * takes those SIGTRAPs for its own. The generated functions are named after
 * their guest addresses (-rdynamic), so the frames read as guest code.
 *
 * Not strictly async-signal-safe -- backtrace() may allocate on first use,
 * so it is primed at install -- which is acceptable for a diagnostic that
 * runs when the process is already stuck. */
static void thread_bt_handler(int sig)
{
    void *frames[48];
    char hdr[64];
    int n, len;
    (void)sig;
    n = backtrace(frames, 48);
    len = snprintf(hdr, sizeof(hdr), "--- thread %ld ---\n", (long)syscall(SYS_gettid));
    if (write(STDERR_FILENO, hdr, (size_t)len) < 0) return;
    backtrace_symbols_fd(frames, n, STDERR_FILENO);
}

static void all_threads_bt_handler(int sig)
{
    DIR *d = opendir("/proc/self/task");
    struct dirent *de;
    long self = (long)syscall(SYS_gettid);
    (void)sig;
    if (!d) return;
    while ((de = readdir(d)) != NULL) {
        long tid = strtol(de->d_name, NULL, 10);
        if (tid <= 0) continue;
        if (tid == self)
            thread_bt_handler(SIGUSR2);
        else
            syscall(SYS_tgkill, (long)getpid(), tid, SIGUSR2);
        usleep(20000);   /* keep the dumps from interleaving */
    }
    closedir(d);
}

static void install_thread_dump(void)
{
    void *prime[1];
    struct sigaction sa;
    backtrace(prime, 1);
    memset(&sa, 0, sizeof(sa));
    sa.sa_flags = SA_RESTART;
    sa.sa_handler = thread_bt_handler;
    sigaction(SIGUSR2, &sa, NULL);
    sa.sa_handler = all_threads_bt_handler;
    sigaction(SIGQUIT, &sa, NULL);
}
